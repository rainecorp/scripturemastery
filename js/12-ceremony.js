/* =========================================================
   SEAL CEREMONY — chest bursts open, relic rises, then the
   climber rides the tower up one floor.
   ========================================================= */
let pendingClimb = null;
function playSealCeremony(v, floorN, campaignId){
  const cer = document.getElementById("ceremony");
  if(!cer){ render(); return; }
  const campaign = primaryCampaignForPassage(v.id, campaignId);
  const r = relicFor(v);
  const d = difficultyForVerse(v);
  const art = (RELIC_IMAGES && r.designed)
    ? `<img class="cer-relic-img" src="relics/${v.id}.webp" alt="">`
    : `<div class="cer-relic-emoji">${r.emoji}</div>`;
  cer.innerHTML = `
    <div class="cer-backdrop"></div>
    <div class="cer-stage">
      <div class="cer-rays"></div>
      <div class="cer-scene">
        <div class="cer-relic-wrap">${art}</div>
        <div class="cer-burst"></div>
        <div class="cer-chest">${chestImg(floorN, 150)}</div>
      </div>
      <div class="cer-text">
        <div class="cer-kicker">✦ Sealed · Chest ${floorN} unlocked ✦</div>
        <div class="cer-name">${r.name}</div>
        <div class="cer-motto">“${r.motto}”</div>
        <div class="cer-ref">${v.ref} · ${d.trim.metal} relic · +50 XP</div>
      </div>
      <button class="btn primary cer-btn" id="cerClimb">Climb ${campaign.name} ▸</button>
      <div class="cer-skip" id="cerShare">📣 share this victory ▸</div>
      <div class="cer-skip" id="cerSkip">or place it on the shelf ▸</div>
    </div>`;
  cer.classList.add("show");
  setTimeout(()=>{ cer.classList.add("phase-shake"); SFX.chest(); }, 150);
  setTimeout(()=>{ cer.classList.add("phase-open"); SFX.seal(); FX.rain({count:110}); }, 1250);
  setTimeout(()=> cer.classList.add("phase-text"), 2050);
  const cerShare = document.getElementById("cerShare");
  if(cerShare) cerShare.onclick = ()=> openSharePop(v);
  const close = ()=>{ cer.classList.remove("show","phase-shake","phase-open","phase-text"); cer.innerHTML = ""; };
  document.getElementById("cerClimb").onclick = ()=>{
    close();
    pendingClimb = {campaignId: campaign.id, floor: floorN};
    view.tab = "towers"; view.campaignId = campaign.id;
    render();
    window.scrollTo({top:0});
  };
  document.getElementById("cerSkip").onclick = ()=>{
    close();
    view.tab = "shelf";
    render();
    window.scrollTo({top:0});
  };
}

/* ---- SQ registry (generated by T2 split; see ROADMAP.md §7) ---- */
Object.defineProperty(SQ,"pendingClimb",{get:()=>pendingClimb,set:v=>{pendingClimb=v;},enumerable:true,configurable:true});
SQ.playSealCeremony = playSealCeremony;
